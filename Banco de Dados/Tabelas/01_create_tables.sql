-- ---------------------------------------------------------------------
-- 1. Tabelas de apoio (catalogos)
-- ---------------------------------------------------------------------

-- Tipos de plugue: CCS2, Type 2, CHAdeMO, GB/T, Outro
create table conector_tipo (
    id    smallint    generated by default as identity,
    nome  varchar(20) not null,
    constraint pk_conector_tipo      primary key (id),
    constraint uq_conector_tipo_nome unique (nome)
);

-- Modelos de carro eletrico usados no filtro "Meu carro"
create table carro_modelo (
    id               smallint     generated by default as identity,
    nome             varchar(60)  not null,
    potencia_max_kw  numeric(5,1) not null,
    constraint pk_carro_modelo        primary key (id),
    constraint uq_carro_modelo_nome   unique (nome),
    constraint ck_carro_modelo_kw     check (potencia_max_kw > 0)
);

-- Quais plugues cada modelo aceita (N:N)
create table carro_modelo_conector (
    carro_modelo_id  smallint not null,
    conector_tipo_id smallint not null,
    constraint pk_carro_modelo_conector primary key (carro_modelo_id, conector_tipo_id),
    constraint fk_cmc_carro    foreign key (carro_modelo_id)
        references carro_modelo (id)  on delete cascade,
    constraint fk_cmc_conector foreign key (conector_tipo_id)
        references conector_tipo (id) on delete restrict
);

-- ---------------------------------------------------------------------
-- 2. Usuarios (motorista ou dono de posto). Visitante nao tem cadastro.
--    A senha fica no Supabase Auth, nao nesta tabela.
-- ---------------------------------------------------------------------
create table usuario (
    id                    integer      generated by default as identity,
    nome                  varchar(80)  not null,
    email                 varchar(120) not null,
    telefone              varchar(20),
    perfil                varchar(12)  not null default 'motorista',
    nome_estabelecimento  varchar(100),
    carro_modelo_id       smallint,
    pontos                integer      not null default 0,
    criado_em             timestamptz  not null default now(),
    constraint pk_usuario        primary key (id),
    constraint uq_usuario_email  unique (email),
    constraint uq_usuario_tel    unique (telefone),
    constraint ck_usuario_perfil check (perfil in ('motorista', 'dono_posto')),
    constraint ck_usuario_pontos check (pontos >= 0),
    constraint ck_usuario_email  check (email like '%_@_%._%'),
    -- dono de posto precisa informar o nome do estabelecimento
    constraint ck_usuario_dono_estab
        check (perfil <> 'dono_posto' or nome_estabelecimento is not null),
    constraint fk_usuario_carro foreign key (carro_modelo_id)
        references carro_modelo (id) on delete set null
);

-- ---------------------------------------------------------------------
-- 3. Eletropostos
-- ---------------------------------------------------------------------
create table posto (
    id                    integer      generated by default as identity,
    nome                  varchar(120) not null,
    endereco              varchar(160) not null,
    bairro                varchar(60),
    latitude              numeric(9,6) not null,
    longitude             numeric(9,6) not null,
    posicao_aproximada    boolean      not null default true,
    status                varchar(12)  not null default 'fora_do_ar',
    status_atualizado_em  timestamptz  not null default now(),
    fonte_status          varchar(10)  not null default 'usuarios',
    confirmacoes          smallint     not null default 0,
    vagas_total           smallint     not null default 1,
    vagas_livres          smallint     not null default 0,
    potencia_kw           numeric(5,1),            -- nulo = "kW a confirmar"
    preco_kwh             numeric(5,2),            -- nulo = "preco a confirmar"
    horario               varchar(60)  not null default 'A confirmar',
    dono_id               integer,                 -- usuario dono (opcional)
    constraint pk_posto            primary key (id),
    constraint ck_posto_latitude   check (latitude  between -90  and 90),
    constraint ck_posto_longitude  check (longitude between -180 and 180),
    constraint ck_posto_status     check (status in ('livre', 'ocupado', 'fora_do_ar')),
    constraint ck_posto_fonte      check (fonte_status in ('usuarios', 'operadora')),
    constraint ck_posto_confirm    check (confirmacoes >= 0),
    constraint ck_posto_vagas_tot  check (vagas_total > 0),
    constraint ck_posto_vagas_liv  check (vagas_livres >= 0),
    constraint ck_posto_vagas      check (vagas_livres <= vagas_total),
    constraint ck_posto_kw         check (potencia_kw is null or potencia_kw > 0),
    constraint ck_posto_preco      check (preco_kwh  is null or preco_kwh >= 0),
    constraint fk_posto_dono foreign key (dono_id)
        references usuario (id) on delete set null
);

-- Plugues disponiveis em cada posto (N:N)
create table posto_conector (
    posto_id         integer  not null,
    conector_tipo_id smallint not null,
    constraint pk_posto_conector primary key (posto_id, conector_tipo_id),
    constraint fk_pc_posto     foreign key (posto_id)
        references posto (id)         on delete cascade,
    constraint fk_pc_conector  foreign key (conector_tipo_id)
        references conector_tipo (id) on delete restrict
);

-- ---------------------------------------------------------------------
-- 4. Parceiros e ofertas
-- ---------------------------------------------------------------------
create table parceiro (
    id    integer      generated by default as identity,
    nome  varchar(100) not null,
    constraint pk_parceiro      primary key (id),
    constraint uq_parceiro_nome unique (nome)
);

create table oferta (
    id          integer      generated by default as identity,
    posto_id    integer      not null,
    parceiro_id integer      not null,
    descricao   varchar(160) not null,
    ativa       boolean      not null default true,
    constraint pk_oferta primary key (id),
    constraint fk_oferta_posto    foreign key (posto_id)
        references posto (id)    on delete cascade,
    constraint fk_oferta_parceiro foreign key (parceiro_id)
        references parceiro (id) on delete restrict
);

-- ---------------------------------------------------------------------
-- 5. Check-in / avaliacao do posto (tela "Avaliar posto")
-- ---------------------------------------------------------------------
create table etiqueta (
    id    smallint    generated by default as identity,
    nome  varchar(60) not null,
    constraint pk_etiqueta      primary key (id),
    constraint uq_etiqueta_nome unique (nome)
);

create table avaliacao (
    id               integer      generated by default as identity,
    posto_id         integer      not null,
    usuario_id       integer      not null,
    status_informado varchar(12)  not null,
    nota             smallint,                       -- 1 a 5, opcional
    comentario       varchar(500),
    foto_url         text,
    pontos_ganhos    smallint     not null default 10,
    criado_em        timestamptz  not null default now(),
    constraint pk_avaliacao primary key (id),
    constraint ck_avaliacao_status check (status_informado in ('livre', 'ocupado', 'fora_do_ar')),
    constraint ck_avaliacao_nota   check (nota is null or nota between 1 and 5),
    constraint ck_avaliacao_pontos check (pontos_ganhos >= 0),
    constraint fk_avaliacao_posto   foreign key (posto_id)
        references posto (id)   on delete cascade,
    constraint fk_avaliacao_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade
);

-- Etiquetas escolhidas em cada avaliacao (N:N)
create table avaliacao_etiqueta (
    avaliacao_id integer  not null,
    etiqueta_id  smallint not null,
    constraint pk_avaliacao_etiqueta primary key (avaliacao_id, etiqueta_id),
    constraint fk_ae_avaliacao foreign key (avaliacao_id)
        references avaliacao (id) on delete cascade,
    constraint fk_ae_etiqueta  foreign key (etiqueta_id)
        references etiqueta (id)  on delete restrict
);

-- ---------------------------------------------------------------------
-- 6. Problemas reportados (+15 pontos)
-- ---------------------------------------------------------------------
create table problema_reportado (
    id          integer      generated by default as identity,
    posto_id    integer      not null,
    usuario_id  integer      not null,
    motivo      varchar(40)  not null,
    criado_em   timestamptz  not null default now(),
    constraint pk_problema_reportado primary key (id),
    constraint ck_problema_motivo check (motivo in (
        'sem_energia', 'conector_danificado', 'pagamento_falhou', 'vaga_ocupada_combustao')),
    constraint fk_problema_posto   foreign key (posto_id)
        references posto (id)   on delete cascade,
    constraint fk_problema_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade
);

-- ---------------------------------------------------------------------
-- 7. Favoritos e alertas "avisar quando liberar" (N:N usuario x posto)
-- ---------------------------------------------------------------------
create table favorito (
    usuario_id integer     not null,
    posto_id   integer     not null,
    criado_em  timestamptz not null default now(),
    constraint pk_favorito primary key (usuario_id, posto_id),
    constraint fk_favorito_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade,
    constraint fk_favorito_posto   foreign key (posto_id)
        references posto (id)   on delete cascade
);

create table alerta_liberacao (
    usuario_id integer     not null,
    posto_id   integer     not null,
    ativo      boolean     not null default true,
    criado_em  timestamptz not null default now(),
    constraint pk_alerta_liberacao primary key (usuario_id, posto_id),
    constraint fk_alerta_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade,
    constraint fk_alerta_posto   foreign key (posto_id)
        references posto (id)   on delete cascade
);

-- ---------------------------------------------------------------------
-- 8. Reserva de vaga (15 min = R$ 3, 30 min = R$ 5, 45 min = R$ 7)
-- ---------------------------------------------------------------------
create table reserva (
    id          integer      generated by default as identity,
    posto_id    integer      not null,
    usuario_id  integer      not null,
    duracao_min smallint     not null,
    valor       numeric(6,2) not null,
    inicio      timestamptz  not null default now(),
    fim         timestamptz  not null,
    status      varchar(10)  not null default 'ativa',
    constraint pk_reserva primary key (id),
    constraint ck_reserva_duracao_valor check (
           (duracao_min = 15 and valor = 3.00)
        or (duracao_min = 30 and valor = 5.00)
        or (duracao_min = 45 and valor = 7.00)),
    constraint ck_reserva_periodo check (fim > inicio),
    constraint ck_reserva_status  check (status in ('ativa', 'concluida', 'cancelada', 'expirada')),
    constraint fk_reserva_posto   foreign key (posto_id)
        references posto (id)   on delete cascade,
    constraint fk_reserva_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade
);

-- ---------------------------------------------------------------------
-- 9. Vantagens: cupons e resgates
-- ---------------------------------------------------------------------
create table cupom (
    id           integer      generated by default as identity,
    titulo       varchar(100) not null,
    descricao    varchar(200),
    custo_pontos integer      not null,
    parceiro_id  integer      not null,
    constraint pk_cupom primary key (id),
    constraint uq_cupom_titulo unique (titulo),
    constraint ck_cupom_custo  check (custo_pontos > 0),
    constraint fk_cupom_parceiro foreign key (parceiro_id)
        references parceiro (id) on delete restrict
);

create table resgate_cupom (
    id           integer     generated by default as identity,
    usuario_id   integer     not null,
    cupom_id     integer     not null,
    codigo       varchar(20) not null,
    resgatado_em timestamptz not null default now(),
    constraint pk_resgate_cupom primary key (id),
    constraint uq_resgate_codigo  unique (codigo),
    constraint uq_resgate_usuario_cupom unique (usuario_id, cupom_id),
    constraint fk_resgate_usuario foreign key (usuario_id)
        references usuario (id) on delete cascade,
    constraint fk_resgate_cupom   foreign key (cupom_id)
        references cupom (id)   on delete restrict
);

-- ---------------------------------------------------------------------
-- 10. Indicadores do painel do dono ("Desempenho hoje")
-- ---------------------------------------------------------------------
create table estatistica_posto_dia (
    posto_id        integer      not null,
    data            date         not null,
    visualizacoes   integer      not null default 0,
    rotas_iniciadas integer      not null default 0,
    checkins        integer      not null default 0,
    kwh_vendidos    numeric(9,2) not null default 0,
    constraint pk_estatistica_posto_dia primary key (posto_id, data),
    constraint ck_estat_valores check (
        visualizacoes >= 0 and rotas_iniciadas >= 0 and checkins >= 0 and kwh_vendidos >= 0),
    constraint fk_estat_posto foreign key (posto_id)
        references posto (id) on delete cascade
);
